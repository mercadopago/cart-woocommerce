/**
 * Coordinates validated creation and Order linkage; native effects belong to the applicator.
 */
final class SmartPixPaymentProcessor
{
    private SmartPixValidator $validator;

    private SmartPixAttemptRepository $attemptRepository;

    private SmartPixOrderClient $client;

    private OrderMetadata $metadata;

    private SmartPixTelemetry $telemetry;

    private ?SmartPixCreationStore $creation;

    /** @var callable(WC_Order): void|null */
    private $onDispatch;

    public function __construct(
        SmartPixValidator $validator,
        SmartPixAttemptRepository $attemptRepository,
        SmartPixOrderClient $client,
        OrderMetadata $metadata,
        ?SmartPixTelemetry $telemetry = null,
        ?SmartPixCreationStore $creation = null,
        ?callable $onDispatch = null
    ) {
        $this->validator         = $validator;
        $this->attemptRepository = $attemptRepository;
        $this->client            = $client;
        $this->metadata          = $metadata;
        $this->telemetry         = $telemetry ?? new SmartPixTelemetry();
        $this->creation = $creation;
        $this->onDispatch = $onDispatch;
    }

    /**
     * The checkout caller must establish the trusted order context and authorization first.
     * Save unrelated pending metadata before calling: the repository forcibly reloads metadata.
     * The client is a server-injected normalized Orders port, never selected by browser input.
     * The candidate idempotency key must also be generated by the server, not submitted by a buyer.
     *
     * @param array<string, mixed> $smartPix
     * @return array<string, mixed> Normalized result; not a WooCommerce checkout response.
     */
    public function process(
        ?WC_Order $order,
        int $expectedOrderId,
        string $surface,
        array $smartPix,
        string $candidateIdempotencyKey,
        ?string $orderKey = null
    ): array {
        if ($order === null) {
            $this->telemetry->error('validation', 'validation', $surface, 'sync_response', 'checkout.order_context: WooCommerce order was not found');
            return $this->failure('validation');
        }

        try {
            $request = $this->validator->validate($order, $expectedOrderId, $surface, $smartPix, $orderKey);
        } catch (InvalidArgumentException $exception) {
            $this->telemetry->error('validation', 'validation', $surface, 'sync_response', SmartPixDiagnostic::exception($exception));
            $result = $this->failure('validation');
            if ($exception instanceof SmartPixExistingPixException) {
                $result['error']['code'] = SmartPixExistingPixException::ERROR_CODE;
            }
            return $result;
        }

        try {
            $attempt = $this->attemptRepository->createOrRead($order, $candidateIdempotencyKey);
            $linkedReference = $this->readLinkedReference($order);
        } catch (InvalidArgumentException $exception) {
            $this->telemetry->error('validation', 'validation', $surface, 'sync_response', SmartPixDiagnostic::exception($exception));
            return $this->failure('validation');
        } catch (RuntimeException $exception) {
            $this->telemetry->error('create', 'persistence', $surface, 'sync_response', SmartPixDiagnostic::exception($exception));
            return $this->failure('persistence');
        }


        // A linked Order requires the separate query path; do not issue another create here.
        if ($linkedReference !== null) {
            return $this->failure('conflict', $linkedReference);
        }

        if ($this->creation !== null && SmartPixCreationStore::hasStarted($order)) {
            return $this->failure(SmartPixCreationStore::failureCategory($order) ?? 'conflict');
        }
        if ($this->creation !== null && !$this->client instanceof SmartPixCreationDispatchClient) {
            return $this->failure('validation');
        }

        $request['payment_contract'] = $attempt['payment_contract'];
        $payment = new SmartPixAuthorizedPayment($smartPix['token'], $smartPix['openFinanceAccountId'], $attempt['idempotency_key']);
        $alreadyStarted = false;
        try {
            if ($this->creation !== null && $this->client instanceof SmartPixCreationDispatchClient) {
                $result = $this->client->create($request, $payment, function () use ($order, $attempt, &$alreadyStarted): void {
                    if (!$this->creation->begin($order, $attempt['idempotency_key'])) {
                        $alreadyStarted = true;
                        if ($this->onDispatch !== null) {
                            ($this->onDispatch)($order);
                        }
                        throw new RuntimeException('creation_already_started');
                    }
                    if ($this->onDispatch !== null) {
                        ($this->onDispatch)($order);
                    }
                });
                if (SmartPixCreationStore::hasStarted($order)) {
                    try {
                        $this->creation->responseReceived($order);
                    } catch (Throwable $observationFailure) {
                        // Optional probe state must never discard the provider response or its identifiers.
                        $this->telemetry->error('create', 'persistence', $surface, 'sync_response', 'create.response_received_marker: ' . SmartPixDiagnostic::exception($observationFailure));
                    }
                }
            } else {
                $result = $this->client->create($request, $payment);
            }
        } catch (Throwable $exception) {
            if ($alreadyStarted || ($this->creation !== null && SmartPixCreationStore::hasStarted($order))) {
                $this->telemetry->error('create', 'internal_error', $surface, 'sync_response', SmartPixDiagnostic::exception($exception));
                return $this->failure($alreadyStarted ? 'conflict' : 'unknown');
            }
            throw $exception;
        }

        if (
            $this->creation !== null && empty($result['order_reference']) && SmartPixCreationStore::hasStarted($order)
            && ($result['outcome'] ?? null) === 'failure' && ($result['state'] ?? null) === 'error'
            && ($result['error']['retryable'] ?? null) === false
            && in_array($result['error']['category'] ?? null, ['validation', 'authentication'], true)
        ) {
            try {
                $this->creation->recordFailure($order, $result['error']['category']);
            } catch (Throwable $persistenceFailure) {
                // An observation failure must not replace the provider's checkout failure.
                $this->telemetry->error('create', 'persistence', $surface, 'sync_response', 'create.failure_marker: ' . SmartPixDiagnostic::exception($persistenceFailure));
            }
        }

        if (($result['outcome'] ?? null) === 'failure') {
            $reference = $result['order_reference'] ?? null;
            if ($reference !== null) {
                if (!$this->isReference($reference)) {
                    $this->telemetry->error('create', 'invalid_contract', $surface, 'sync_response', 'create.response: failed result contains an invalid order_reference');
                    return $this->failure('invalid_response');
                }
                // The injected normalized port owns response correlation. A known Order
                // remains queryable even when its financial state is not yet supported.
                $linkageFailure = $this->linkReference($order, $reference, $surface);
                if ($linkageFailure !== null) {
                    return $linkageFailure;
                }
            }
            return $result;
        }
        if (
            ($result['outcome'] ?? null) !== 'success'
            || (
                ($result['state'] ?? null) !== 'processing'
                && !$this->isAccreditedCreate($result, $request['amount'])
            )
            || !$this->isReference($result['order_reference'] ?? null)
        ) {
            $this->telemetry->error('create', 'invalid_contract', $surface, 'sync_response', 'create.response: result must contain a valid order_reference and processing or fully accredited payment');
            return $this->failure('invalid_response');
        }

        $linkageFailure = $this->linkReference($order, $result['order_reference'], $surface);
        return $linkageFailure ?? $result;
    }

    /**
     * The create contract currently supports one payment matching the validated server total.
     * This preserves approval facts without completing the WooCommerce payment here.
     *
     * @param array<string, mixed> $result Already normalized by the injected Orders port.
     * @param array<string, string> $expectedAmount Validated authoritative server amount.
     */
    private function isAccreditedCreate(array $result, array $expectedAmount): bool
    {
        $payments = $result['payments'] ?? null;
        if (
            ($result['state'] ?? null) !== 'terminal_success'
            || !array_key_exists('error', $result) || $result['error'] !== null
            || !is_array($payments) || count($payments) !== 1 || array_keys($payments) !== [0]
            || !is_array($payments[0])
        ) {
            return false;
        }

        $payment = $payments[0];
        $amount = $payment['amount'] ?? null;
        return ($payment['state'] ?? null) === 'approved'
            && $this->isReference($payment['reference'] ?? null)
            && is_array($amount)
            && ($amount['value'] ?? null) === $expectedAmount['value']
            && ($amount['currency'] ?? null) === $expectedAmount['currency'];
    }

    /** @return array<string, mixed>|null Null means the reference survived a fresh read. */
    private function linkReference(WC_Order $order, string $reference, string $surface): ?array
    {
        try {
            $order->read_meta_data(true);
            $currentReference = $this->readLinkedReference($order);
            if ($currentReference !== null && !hash_equals($currentReference, $reference)) {
                $this->telemetry->error('create', 'invalid_contract', $surface, 'sync_response', 'create.link_reference: response order_reference differs from the persisted order_reference');
                return $this->failure('linkage_mismatch', $reference);
            }
            $references = $this->client instanceof SmartPixCreationReferences ? $this->client->creationReferences() : null;
            if ($references !== null && $references['order_reference'] !== $reference) {
                $this->telemetry->error('create', 'invalid_contract', $surface, 'sync_response', 'create.link_reference: provider reference set belongs to a different order_reference');
                return $this->failure('linkage_mismatch', $reference);
            }
            if ($currentReference === null) {
                if ($references === null) {
                    $this->metadata->linkSmartPixOrder($order, $reference, time());
                } else {
                    $this->metadata->linkSmartPixOrder($order, $reference, time(), $references);
                }
            } elseif ($references !== null) {
                $this->metadata->persistSmartPixReferences($order, $references);
            }
            $order->read_meta_data(true);
            if ($this->readLinkedReference($order) !== $reference || !$this->referencesPersisted($order, $references)) {
                $this->telemetry->error('create', 'persistence', $surface, 'sync_response', 'create.persist_references: saved order/payment references did not survive a fresh metadata read');
                return $this->failure('persistence', $reference);
            }
        } catch (InvalidArgumentException $exception) {
            $this->telemetry->error('create', 'invalid_contract', $surface, 'sync_response', 'create.link_reference: ' . SmartPixDiagnostic::exception($exception));
            return $this->failure('invalid_response', $reference);
        } catch (RuntimeException $exception) {
            $this->telemetry->error('create', 'persistence', $surface, 'sync_response', 'create.persist_references: ' . SmartPixDiagnostic::exception($exception));
            return $this->failure('persistence', $reference);
        }

        return null;
    }

    /** @param array<string, string>|null $references */
    private function referencesPersisted(WC_Order $order, ?array $references): bool
    {
        foreach ([
            'payment_reference' => 'getPpPaymentId',
            'provider_order_reference' => 'getMpOrderId',
            'transaction_intent_reference' => 'getTransactionIntentId',
        ] as $key => $getter) {
            if (isset($references[$key]) && $this->metadata->{$getter}($order) !== $references[$key]) {
                return false;
            }
        }
        return true;
    }

    private function readLinkedReference(WC_Order $order): ?string
    {
        $reference = $this->metadata->getPpOrderId($order);
        if ($reference === '' || $reference === null) {
            return null;
        }
        if (!$this->isReference($reference)) {
            throw new RuntimeException('Invalid Smart Pix persisted reference.');
        }

        return $reference;
    }

    /** @param mixed $reference */
    private function isReference($reference): bool
    {
        return is_string($reference)
            && strlen($reference) <= 128
            && preg_match('/^[A-Za-z0-9][A-Za-z0-9_-]{2,127}$/D', $reference) === 1;
    }

    /** @return array<string, mixed> */
    private function failure(string $category, ?string $reference = null): array
    {
        return [
            'outcome'         => 'failure',
            'state'           => 'error',
            'order_reference' => $reference,
            'eligibility'     => null,
            'authorization'   => null,
            'payments'        => [],
            'error'           => [
                'category' => $category,
                'code' => 'SMART_PIX_' . strtoupper($category),
                'retryable' => false,
            ],
        ];
    }
}
